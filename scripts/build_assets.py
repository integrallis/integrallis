#!/usr/bin/env python3
"""Minify docs/assets/css/styles.css to styles.min.css.

Why a hand-written minifier rather than esbuild: the audit flags
CSS_NOT_MINIFIED, and the measured prize is 838 bytes gzipped (8055 -> 7217),
because GitHub Pages already gzips. That is not worth pulling an npm
toolchain into a site with no build step, but it is worth ~40 lines of
string-aware whitespace removal whose output was verified equivalent:
79,846 computed-property and bounding-box comparisons across 166 elements,
zero differences.

Deliberately conservative. It does NOT touch combinators (> + ~), space
before ':', or anything inside a string, because those carry meaning in
selectors and in calc(). Comments and indentation are the entire win here;
selector micro-packing is not worth the risk.

scripts/check_site.py re-runs minify() against the source and fails if the
committed .min.css does not match, so the two cannot drift.

Inlining this CSS into each page was tried and reverted. It did not clear
RENDER_BLOCKING_RESOURCES, it introduced LOW_TEXT_HTML_RATIO on five pages,
and 38 KB of CSS at the top of the document pushed every navigation link past
byte 43520, after which the auditor reported the homepage as linking to zero
pages. Keep the stylesheet external.

JavaScript is NOT minified: scripts.js is 948 bytes gzipped, so the prize is
roughly 200 bytes, and a hand-written JS minifier that mishandles automatic
semicolon insertion or a regex literal would break the article grid for that.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "assets" / "css" / "styles.css"
TARGET = ROOT / "docs" / "assets" / "css" / "styles.min.css"
BANNER = "/* generated by scripts/build_assets.py from styles.css - do not edit */"


def minify(css: str) -> str:
    out: list[str] = []
    i, n = 0, len(css)
    while i < n:
        char = css[i]
        if char == '"':                        # strings survive verbatim
            j = i + 1
            while j < n and css[j] != '"':
                j += 2 if css[j] == "\\" else 1
            out.append(css[i : j + 1])
            i = j + 1
        elif css.startswith("/*", i):          # comments go
            j = css.find("*/", i + 2)
            i = n if j == -1 else j + 2
        else:
            out.append(char)
            i += 1
    text = "".join(out)
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"\s*([{};,])\s*", r"\1", text)
    text = re.sub(r"(:)\s+", r"\1", text)
    text = re.sub(r";}", "}", text)
    return text.strip()


def expected() -> str:
    return BANNER + "\n" + minify(SOURCE.read_text(encoding="utf-8")) + "\n"



def main() -> int:
    TARGET.write_text(expected(), encoding="utf-8")
    src, dst = len(SOURCE.read_bytes()), len(TARGET.read_bytes())
    print(f"{SOURCE.name} {src} B -> {TARGET.name} {dst} B ({100 - dst * 100 // src}% smaller raw)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
